#!/usr/bin/env python3
"""
Generate the entity-relationship diagram for buylog into doc/.

Always writes the text formats, which need nothing beyond eralchemy:

    doc/er_model.md   Mermaid ER diagram (renders inline on GitHub)
    doc/er_model.er   eralchemy markup
    doc/er_model.dot  Graphviz dot source

The SVG additionally needs Graphviz (the `dot` binary plus pygraphviz or
graphviz). It is written when they are available and skipped with a clear
message when they are not, rather than leaving a stale diagram in place.

Usage:
    python scripts/gen_diagram.py
"""

import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DOC_DIR = PROJECT_ROOT / "doc"

sys.path.insert(0, str(PROJECT_ROOT / "src"))


def graphviz_available() -> bool:
    """Whether Graphviz can render an image."""
    if shutil.which("dot") is None:
        return False
    try:
        import pygraphviz  # noqa: F401
    except ImportError:
        try:
            import graphviz  # noqa: F401
        except ImportError:
            return False
    return True


def mermaid_type(column) -> str:
    """A short, mermaid-safe type name for a column."""
    name = type(column.type).__name__.lower()
    return {
        "integer": "int",
        "float": "float",
        "string": "string",
        "varchar": "string",
        "text": "string",
        "date": "date",
        "datetime": "datetime",
        "boolean": "bool",
    }.get(name, name)


def build_mermaid(metadata) -> str:
    """
    Render ``metadata`` as a Mermaid ``erDiagram``.

    Written by hand rather than via eralchemy's mermaid mode, which emits
    invalid cardinalities and links out to the mermaid.ink service.
    """
    lines = ["erDiagram"]

    # Relationships first, so the diagram reads top-down from the schema shape.
    for table in metadata.sorted_tables:
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            parent = fk.column.table.name
            # An optional FK is "zero or one", a required one is "exactly one".
            left = "|o" if fk.parent.nullable else "||"
            lines.append(f"    {parent} {left}--o{{ {table.name} : {fk.parent.name}")

    for table in metadata.sorted_tables:
        lines.append(f"    {table.name} {{")
        for column in table.columns:
            keys = []
            if column.primary_key:
                keys.append("PK")
            if column.foreign_keys:
                keys.append("FK")
            suffix = f" {','.join(keys)}" if keys else ""
            lines.append(f"        {mermaid_type(column)} {column.name}{suffix}")
        lines.append("    }")

    return "\n".join(lines)


def main() -> int:
    from eralchemy import render_er

    from buylog.models import Base

    # Import audit so AuditLog is part of the diagram, exactly as it is part
    # of the schema init_db() creates.
    import buylog.audit  # noqa: F401

    DOC_DIR.mkdir(parents=True, exist_ok=True)

    for name in ("er_model.er", "er_model.dot"):
        target = DOC_DIR / name
        render_er(Base, str(target), title="buylog data model")
        print(f"wrote {target.relative_to(PROJECT_ROOT)}")

    md = DOC_DIR / "er_model.md"
    md.write_text(
        "# buylog data model\n\n"
        "Generated by `make diagram` (`scripts/gen_diagram.py`). Do not edit by hand.\n\n"
        f"```mermaid\n{build_mermaid(Base.metadata)}\n```\n"
    )
    print(f"wrote {md.relative_to(PROJECT_ROOT)}")

    svg = DOC_DIR / "er_model.svg"
    if graphviz_available():
        render_er(Base, str(svg), title="buylog data model")
        print(f"wrote {svg.relative_to(PROJECT_ROOT)}")
    else:
        print(
            f"skipped {svg.relative_to(PROJECT_ROOT)}: Graphviz not available.\n"
            "  Install the 'dot' binary (e.g. `apt install graphviz`) and\n"
            "  `uv add --dev pygraphviz`, then re-run `make diagram`."
        )

    print(f"{len(Base.metadata.tables)} tables diagrammed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
